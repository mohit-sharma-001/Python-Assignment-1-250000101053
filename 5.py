# Question 5: Write a program to demonstrate the use of valid and invalid Python identifiers.

# Valid identifiers:
user_name = "Alice"
_age = 20
totalScore1 = 95

print("Valid identifiers:")
print("user_name:", user_name)
print("_age:", _age)
print("totalScore1:", totalScore1)

# Invalid identifiers (cannot be used directly in code as variable names):
# 1st_rank = 1         (Cannot start with a digit)
# my-variable = 10     (Hyphen not allowed)
# class = "CS"         (Reserved keyword)
# user name = "Bob"    (Spaces not allowed)
print("\nExamples of invalid identifiers (commented in code): 1st_rank, my-variable, class, user name")
