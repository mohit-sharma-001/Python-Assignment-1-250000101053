# Question 40: Write a program to demonstrate the use of Boolean variables.

is_python_fun = True
is_difficult = False

print("is_python_fun:", is_python_fun)
print("is_difficult:", is_difficult)
print("AND condition:", is_python_fun and is_difficult)
print("OR condition:", is_python_fun or is_difficult)
print("NOT condition:", not is_difficult)
