# Question 29: Write a program to find the minimum and maximum values from a set of numerical values using built-in functions.

numbers = [45, 12, 89, 7, 63, 104, 32]

min_val = min(numbers)
max_val = max(numbers)

print("List of numbers:", numbers)
print("Minimum value:", min_val)
print("Maximum value:", max_val)
