# Question 38: Write a program to display the length of a string, list, tuple and dictionary using len().

sample_str = "Programming"
sample_list = [1, 2, 3, 4, 5]
sample_tuple = ("a", "b", "c")
sample_dict = {"x": 10, "y": 20}

print("Length of string:", len(sample_str))
print("Length of list:", len(sample_list))
print("Length of tuple:", len(sample_tuple))
print("Length of dictionary:", len(sample_dict))
