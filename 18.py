# Question 18: Write a program to calculate the volume of a cube and a cuboid.

# Volume of cube = side^3
side = 4.0
volume_cube = side ** 3

# Volume of cuboid = length * breadth * height
length = 6.0
breadth = 4.0
height = 3.0
volume_cuboid = length * breadth * height

print(f"Side of cube: {side}")
print(f"Volume of cube: {volume_cube}")
print(f"Dimensions of cuboid: {length} x {breadth} x {height}")
print(f"Volume of cuboid: {volume_cuboid}")
