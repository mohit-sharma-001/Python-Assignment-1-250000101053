# Question 41: Write a program to create variables using different naming conventions and display their values.

# camelCase
studentName = "John"

# PascalCase
StudentRollNumber = 101

# snake_case
course_subject_name = "Python Programming"

# SCREAMING_SNAKE_CASE (often used for constants)
MAX_SCORE = 100

print("camelCase (studentName):", studentName)
print("PascalCase (StudentRollNumber):", StudentRollNumber)
print("snake_case (course_subject_name):", course_subject_name)
print("SCREAMING_SNAKE_CASE (MAX_SCORE):", MAX_SCORE)
