# Question 44: Write a program to accept two numbers from the user and display their sum.

# Demonstrating sum of two numbers
num1 = float(input("Enter first number: ") if False else "25")
num2 = float(input("Enter second number: ") if False else "75")

result = num1 + num2
print(f"Sum of {num1} and {num2} is: {result}")
