# Question 47: Write a program to demonstrate the use of list(), tuple() and dict() constructors.

# list() constructor
l = list((1, 2, 3, 4))
print("List from tuple:", l, type(l))

# tuple() constructor
t = tuple([5, 6, 7, 8])
print("Tuple from list:", t, type(t))

# dict() constructor
d = dict(name="Alice", age=22)
print("Dict from constructor:", d, type(d))
